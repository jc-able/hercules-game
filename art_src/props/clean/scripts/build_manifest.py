def glb_info(path):
    scene = trimesh.load(path, force="scene")
    mesh = scene.to_geometry() if hasattr(scene, "to_geometry") else scene.dump(concatenate=True)
    g = pygltflib.GLTF2().load(path)
    tex = []
    blob = g.binary_blob()
    for im in g.images:
        bv = g.bufferViews[im.bufferView]
        data = blob[bv.byteOffset or 0:(bv.byteOffset or 0) + bv.byteLength]
        tex.append(list(Image.open(io.BytesIO(data)).size))
    return mesh, tex, len(g.materials)


def r3(v):
    return [round(float(x), 3) for x in v]


manifest = {}
problems = []
for n in NAMES:
    path = f"{REPO}/game/assets/props/{n}.glb"
    if not os.path.exists(path):
        problems.append(f"{n}: missing")
        continue
    st = json.load(open(f"{REPO}/work/props/stats/{n}.json"))
    mesh, tex, nmat = glb_info(path)
    v = np.asarray(mesh.vertices)
    mn, mx = v.min(0), v.max(0)
    size = mx - mn
    tris = int(len(mesh.faces))
    if tris != st["tris"]:
        problems.append(f"{n}: tris trimesh {tris} vs blender {st['tris']}")
    if abs(mn[1]) > 1e-3 or abs((mn[0] + mx[0]) / 2) > 1e-3 or abs((mn[2] + mx[2]) / 2) > 1e-3:
        problems.append(f"{n}: not grounded/centred {mn} {mx}")
    e = {"size": r3(size), "triangles": tris, "collision": st["collision"]}
    if n.startswith("statue"):
        foot = v[v[:, 1] < mn[1] + 0.08 * size[1]]
        fmn, fmx = foot.min(0), foot.max(0)
        e["collision_size"] = r3([fmx[0] - fmn[0], size[1], fmx[2] - fmn[2]])
        e["collision_offset"] = r3([(fmn[0] + fmx[0]) / 2, size[1] / 2, (fmn[2] + fmx[2]) / 2])
    else:
        e["collision_size"] = st.get("collision_size")
        e["collision_offset"] = st.get("collision_offset")
    if "collision_parts" in st:
        e["collision_parts"] = st["collision_parts"]
        e["opening_height"] = st["opening_height"]
    e["texture_px"] = tex[0][0] if tex else None
    e["materials"] = nmat
    e["notes"] = NOTES[n]
    manifest[n] = e

manifest_doc = {
    "_conventions": "Godot axes, metres. Origin at the base centre (y=0 is the ground), front faces +Z. "
                    "box collision_size = [x, y, z]; cylinder collision_size = [radius, height]; "
                    "collision_offset = centre of the shape relative to the prop origin. "
                    "Generated by work/props/build_manifest.py.",
}
manifest_doc.update(manifest)
with open(f"{REPO}/game/assets/props/props.json", "w") as f:
    json.dump(manifest_doc, f, indent=1)
for n, e in manifest.items():
    print(f"{n:14s} tris={e['triangles']:6d} size={e['size']} tex={e['texture_px']} mats={e['materials']} "
          f"col={e['collision']} {e['collision_size']}")
print("PROBLEMS:", problems or "none")
